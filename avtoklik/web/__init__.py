"""Веб-клиент «АвтоКлик»: витрина (D1) и карточка автомобиля (C1).

Почему серверный рендер, а не одностраничное приложение
------------------------------------------------------
В ТЗ (3.1) роль веба описана как «SEO-витрина и точка входа»: карточки
объявлений обязаны индексироваться, иначе классифайд теряет главный канал
бесплатного трафика. Значит, HTML должен приходить готовым, а не собираться
в браузере. Отсюда — рендер шаблонами на том же FastAPI, который уже отдаёт
API: одна кодовая база, один прогон тестов, одна сборка.

Это сознательное отступление от 3.1, где веб-клиент предлагался на Next.js.
Отдельный фронтенд-стек стоит второго языка, второго набора зависимостей и
второго пайплайна CI — а взамен даёт то же самое SSR. Когда появятся личный
кабинет и интерактив сверх карточки, Next.js вернётся в обсуждение: JSON-API
никуда не делся и остаётся точкой входа для любого другого клиента.

Что сюда не входит
------------------
Мобильные приложения (Flutter по 3.1) и платный флоу проверки. Карточка
показывает оффер и передаёт управление API проверки; сам «рентген» (B2) —
следующий шаг.
"""

