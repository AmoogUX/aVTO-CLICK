"""Нормализация и валидация VIN.

VIN — уровень 0 каскада дедупликации (§5.2 технической документации): точное
совпадение нормализованных VIN даёт уверенность 0.99, а расхождение валидных
VIN — жёсткий запрет на склейку.

**Почему нормализация не сводится к ``upper()``.** В VIN по стандарту ISO 3779
не бывает букв ``I``, ``O`` и ``Q`` — их исключили как раз потому, что они
неотличимы от ``1``, ``0`` и ``0``. Значит, встретив их, мы не отвергаем ввод, а
чиним: это не «неверный VIN», а гарантированная опечатка распознавания или
ручного набора. Заодно переводим кириллические близнецы (пользователь копирует
VIN из объявления в русской раскладке).
"""

from __future__ import annotations

__all__ = [
    "VIN_FORBIDDEN_LETTERS",
    "VIN_LENGTH",
    "has_valid_check_digit",
    "is_valid_vin",
    "normalize_vin",
    "vin_check_digit",
]

VIN_LENGTH = 17
"""Длина VIN по ISO 3779 — ровно 17 символов."""

VIN_FORBIDDEN_LETTERS = frozenset("IOQ")
"""Буквы, которых в VIN не бывает: визуально совпадают с 1, 0 и 0."""

_DIGITS = "0123456789"

_REPAIR = {"I": "1", "O": "0", "Q": "0"}
"""Опечатки, которые чиним молча: запрещённая буква → её цифра-близнец."""

_CYRILLIC_TO_LATIN = {
    "А": "A",
    "В": "B",
    "Е": "E",
    "К": "K",
    "М": "M",
    "Н": "H",
    "О": "O",
    "Р": "P",
    "С": "C",
    "Т": "T",
    "У": "Y",
    "Х": "X",
    "З": "3",
}
"""Кириллица из русской раскладки → латиница VIN (``О`` затем починится в ``0``)."""

_TRANSLIT: dict[str, int] = {
    "A": 1,
    "B": 2,
    "C": 3,
    "D": 4,
    "E": 5,
    "F": 6,
    "G": 7,
    "H": 8,
    "J": 1,
    "K": 2,
    "L": 3,
    "M": 4,
    "N": 5,
    "P": 7,
    "R": 9,
    "S": 2,
    "T": 3,
    "U": 4,
    "V": 5,
    "W": 6,
    "X": 7,
    "Y": 8,
    "Z": 9,
}
"""Транслитерация букв в числа для расчёта контрольной цифры."""

_WEIGHTS = (8, 7, 6, 5, 4, 3, 2, 10, 0, 9, 8, 7, 6, 5, 4, 3, 2)
"""Позиционные веса. На 9-й позиции вес 0 — сама контрольная цифра не участвует."""

_CHECK_DIGIT_POSITION = 8
"""Индекс контрольной цифры (9-я позиция, считая с единицы)."""

_ALLOWED = frozenset(_TRANSLIT) | frozenset(_DIGITS)


def normalize_vin(raw: str) -> str | None:
    """Приводит VIN к канону: 17 символов, верхний регистр, без I, O, Q.

    Args:
        raw: то, что ввёл пользователь или отдала площадка (возможно с
            пробелами, дефисами, в кириллице, с ``I``/``O``/``Q``).

    Returns:
        Канонический VIN либо ``None``, если строка не похожа на VIN (не та
        длина или посторонние символы). Контрольная цифра здесь **не**
        проверяется — это отдельное решение, см. :func:`is_valid_vin`.
    """
    upper = raw.upper()
    chars: list[str] = []
    for ch in upper:
        latin = _CYRILLIC_TO_LATIN.get(ch, ch)
        if latin.isspace() or latin in {"-", "_", ".", "/"}:
            # Разделители из вставки из буфера смысла не несут.
            continue
        fixed = _REPAIR.get(latin, latin)
        if fixed not in _ALLOWED:
            return None
        chars.append(fixed)

    if len(chars) != VIN_LENGTH:
        return None
    return "".join(chars)


def vin_check_digit(vin: str) -> str:
    """Считает контрольную цифру VIN (9-я позиция) по стандарту ISO 3779.

    Буквы переводятся в числа по таблице транслитерации, каждая позиция
    умножается на свой вес, сумма берётся по модулю 11; остаток 10 записывается
    как ``X``.

    Args:
        vin: **уже нормализованный** VIN из 17 разрешённых символов.

    Returns:
        Одну из строк ``"0"``…``"9"`` или ``"X"``.

    Raises:
        ValueError: если строка не нормализована (не та длина или чужие символы).
    """
    if len(vin) != VIN_LENGTH or any(ch not in _ALLOWED for ch in vin):
        raise ValueError("VIN должен быть нормализован перед расчётом контрольной цифры")

    total = 0
    for ch, weight in zip(vin, _WEIGHTS, strict=True):
        value = int(ch) if ch in _DIGITS else _TRANSLIT[ch]
        total += value * weight

    remainder = total % 11
    return "X" if remainder == 10 else str(remainder)


def has_valid_check_digit(raw: str) -> bool:
    """Проверяет только контрольную цифру (после нормализации)."""
    vin = normalize_vin(raw)
    if vin is None:
        return False
    return vin[_CHECK_DIGIT_POSITION] == vin_check_digit(vin)


def is_valid_vin(raw: str, strict_checksum: bool = False) -> bool:
    """Проверяет VIN. По умолчанию — **без** контрольной цифры, и это осознанно.

    Контрольная цифра обязательна только для североамериканских VIN (FMVSS 115 /
    49 CFR 565). Европейские и азиатские производители — а это подавляющее
    большинство машин на российском вторичном рынке — 9-ю позицию заполняют
    произвольно, и строгая проверка отбраковала бы, например, реальный BMW
    ``WBA3A5C51DF598900``. Поэтому:

    * ``strict_checksum=False`` (по умолчанию) — проверяем длину, алфавит и
      отсутствие ``I``/``O``/``Q``. Этого достаточно, чтобы использовать VIN как
      ключ склейки: ложное совпадение двух разных 17-символьных строк невозможно;
    * ``strict_checksum=True`` — дополнительно сверяем контрольную цифру. Этот
      режим нужен там, где цена ошибки высока и VIN заведомо североамериканский:
      ручной ввод пользователем с последующим платным запросом в реестр,
      антифрод-проверки, приём VIN из ненадёжного источника (OCR по фото).

    Args:
        raw: исходная строка VIN.
        strict_checksum: включить проверку контрольной цифры.

    Returns:
        ``True``, если VIN пригоден к использованию в выбранном режиме.
    """
    vin = normalize_vin(raw)
    if vin is None:
        return False
    if not strict_checksum:
        return True
    return vin[_CHECK_DIGIT_POSITION] == vin_check_digit(vin)
