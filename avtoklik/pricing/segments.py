"""Статистика сегмента — то, на чём стоит оценка цены до появления моделей.

Раздел 5.3.4 описывает четыре шага выхода из холодного старта. Здесь
реализован **шаг 1**: справедливая цена — медиана активных объявлений
сегмента (модель + поколение + год ± 1) с поправкой на пробег, а срок
продажи — экспозиция сегмента с поправкой на отклонение цены от медианы.
Никакого обучения: обучать на нуле сделок нечему.

Главное правило шага 1 и причина, по которой этот модуль вообще существует
отдельно: **сегмент меньше тридцати объявлений не даёт оценки вовсе**. Не
«оценку с низкой уверенностью», не «примерно», а пусто. На редкой модели
выдуманное число дороже молчания: продавец поставит его в объявление, а
покупатель увидит бейдж «в рынке», которого не существует.

Данные сегментов — фикстуры исторического среза (шаг 0: сбор за 60 дней до
запуска). Когда Collector начнёт складывать реальные срезы, поменяется
источник :func:`segment_for`, а не формулы.
"""

from __future__ import annotations

from dataclasses import dataclass

__all__ = [
    "MIN_SEGMENT_LISTINGS",
    "SegmentStats",
    "segment_for",
]

#: Порог из 5.3.4: ниже него сегмент не расширяем автоматически, а честно
#: отвечаем «мало данных». Тридцать — это то, при котором медиана перестаёт
#: скакать от одного дорогого объявления.
MIN_SEGMENT_LISTINGS = 30


@dataclass(frozen=True, slots=True)
class SegmentStats:
    """Срез сегмента: что мы знаем о похожих машинах в продаже.

    `price_per_1000km` — наклон простой линейной регрессии цены по пробегу
    внутри сегмента (5.3.4, шаг 1). Один коэффициент, а не модель: на срезе
    из двух сотен объявлений большего и не выжать.

    `days_elasticity` — насколько дорожает ожидание при цене выше медианы:
    срок умножается на `exp(elasticity × отклонение_в_процентах)`. Величина
    **подогнана под три опорные точки экрана E3 из макета, а не оценена по
    данным**, и это её главное свойство: как только появятся факты продаж
    (5.3.2 — свои объявления дают их точно), она пересчитывается по ним.
    """

    #: Человеческое название сегмента для объяснения оценки.
    title: str
    listings_count: int
    median_price_rub: int
    median_mileage_km: int
    price_per_1000km: int
    median_days_on_market: float
    days_elasticity: float

    @property
    def is_thick_enough(self) -> bool:
        """Хватает ли объявлений, чтобы вообще что-то утверждать."""
        return self.listings_count >= MIN_SEGMENT_LISTINGS


# Сегмент эталонного экрана E3: «214 похожих в продаже · медиана 1 305 т».
# Числа взяты из макета, и на них же проверяется весь расчёт: рекомендация
# обязана давать 1 292 000 ₽ и ≈12 дней, края шкалы — 1 249 т/≈6 дней и
# 1 340 т/≈25 дней.
_OCTAVIA_A7 = SegmentStats(
    title="Škoda Octavia A7, 2016–2018",
    listings_count=214,
    median_price_rub=1_305_000,
    median_mileage_km=118_000,
    price_per_1000km=800,
    median_days_on_market=14.5,
    days_elasticity=0.2046,
)

# Сегмент эталона витрины. Объявлений мало намеренно: на нём проверяется, что
# продукт умеет отвечать «оценки нет», а не подставлять медиану от трёх машин.
_RIO_III = SegmentStats(
    title="Kia Rio III, 2016–2018",
    listings_count=18,
    median_price_rub=845_000,
    median_mileage_km=95_000,
    price_per_1000km=1_100,
    median_days_on_market=11.0,
    days_elasticity=0.2046,
)

_SEGMENTS: dict[str, SegmentStats] = {
    "skoda-octavia-a7": _OCTAVIA_A7,
    "kia-rio-3": _RIO_III,
}


def segment_for(model_id: str | None) -> SegmentStats | None:
    """Срез сегмента по модели. ``None`` — среза нет, оценки не будет.

    Год в ключ пока не входит: фикстурные срезы описаны интервалом лет целиком.
    Когда срезы начнёт собирать Collector, ключом станет пара «поколение + год».
    """
    if not model_id:
        return None
    return _SEGMENTS.get(model_id)
